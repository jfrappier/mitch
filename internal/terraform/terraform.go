// Package terraform writes Terraform configuration that manages the Vault
// configuration found in one saved scan, plus import blocks so Terraform
// adopts what already exists instead of creating it again.
//
// It covers namespaces, secrets engines, auth methods, ACL policies and
// audit devices. It never writes secret values: KV data, role credentials
// and passwords are out of scope on purpose.
//
// Provider docs (terraform-provider-vault):
// https://registry.terraform.io/providers/hashicorp/vault/latest/docs
package terraform

import (
	"fmt"
	"path"
	"regexp"
	"sort"
	"strings"
	"time"

	"github.com/jfrappier/mitch/internal/scan"
)

// File names written to the output directory.
const (
	fileVersions   = "versions.tf"
	fileProviders  = "providers.tf"
	fileNamespaces = "namespaces.tf"
	fileMounts     = "secrets_engines.tf"
	fileAuth       = "auth_methods.tf"
	filePolicies   = "policies.tf"
	fileAudit      = "audit_devices.tf"
	fileImports    = "imports.tf"
	policyFolder   = "policies"
)

// Mounts that Vault creates itself and that cannot be enabled, disabled or
// moved, so Terraform must not manage them.
// This is Vault's own "protectedMounts" list (vault/mount.go). Vault 2.x adds
// agent-registry/, which every Vault 2.x server has.
// Source: https://github.com/hashicorp/vault/blob/main/vault/mount.go
// Docs: https://developer.hashicorp.com/vault/docs/secrets/cubbyhole and
// https://developer.hashicorp.com/vault/docs/secrets/identity
var builtInSecretsEngines = map[string]bool{"sys/": true, "identity/": true, "cubbyhole/": true, "agent-registry/": true}

// builtInAuthMethods are auth methods Vault creates itself.
var builtInAuthMethods = map[string]bool{"token/": true}

// rootPolicyName is the built-in policy that cannot be changed, so it is skipped.
// Docs: https://developer.hashicorp.com/vault/docs/concepts/policies#root-policy
const rootPolicyName = "root"

// Result is the generated configuration.
type Result struct {
	// Files maps a path inside the output directory to its content.
	Files map[string][]byte

	// Counts says how many resources of each kind were written.
	Counts Counts

	// Skipped explains parts of the scan that were not turned into Terraform.
	Skipped []string
}

// Counts is how many resources of each kind were written.
type Counts struct {
	Namespaces     int
	SecretsEngines int
	AuthMethods    int
	Policies       int
	AuditDevices   int
}

// Generate builds the Terraform configuration for one saved scan.
func Generate(scanID string, inventory scan.Inventory) (Result, error) {
	generator := newGenerator(scanID, inventory)

	err := generator.generate()
	if err != nil {
		return Result{}, err
	}
	return generator.result(), nil
}

// generator holds the files while they are being written.
type generator struct {
	scanID    string
	inventory scan.Inventory

	header     string
	providers  *strings.Builder
	namespaces *strings.Builder
	mounts     *strings.Builder
	auth       *strings.Builder
	policies   *strings.Builder
	audit      *strings.Builder
	imports    *strings.Builder

	policyFiles map[string][]byte
	usedNames   map[string]bool
	aliases     map[string]string
	counts      Counts
	skipped     []string
}

func newGenerator(scanID string, inventory scan.Inventory) *generator {
	header := fmt.Sprintf("# Generated by Mitch from scan %s of %s, started %s.\n# Review before applying. See docs/terraform.md in the Mitch repository.\n",
		scanID, inventory.VaultAddress, inventory.StartedAt.UTC().Format(time.RFC3339))
	return &generator{
		scanID:      scanID,
		inventory:   inventory,
		header:      header,
		providers:   &strings.Builder{},
		namespaces:  &strings.Builder{},
		mounts:      &strings.Builder{},
		auth:        &strings.Builder{},
		policies:    &strings.Builder{},
		audit:       &strings.Builder{},
		imports:     &strings.Builder{},
		policyFiles: map[string][]byte{},
		usedNames:   map[string]bool{},
		aliases:     map[string]string{},
		skipped:     []string{},
	}
}

// generate writes every part of the configuration.
func (g *generator) generate() error {
	g.writeProviders()

	for _, namespace := range g.inventory.Namespaces {
		if namespace.Path != "" {
			g.writeNamespace(namespace.Path)
		}
		g.noteSkippedChecks(namespace.Path)
		for _, mount := range namespace.SecretsEngines {
			g.writeSecretsEngine(namespace.Path, mount)
		}
		for _, mount := range namespace.AuthMethods {
			g.writeAuthMethod(namespace.Path, mount)
		}
		for _, policy := range namespace.ACLPolicies {
			err := g.writePolicy(namespace.Path, policy)
			if err != nil {
				return err
			}
		}
	}

	if g.inventory.AuditDevices == nil {
		g.skipped = append(g.skipped, "audit devices: not collected (the scan ran without --sudo)")
	}
	for _, device := range g.inventory.AuditDevices {
		g.writeAuditDevice(device)
	}
	return nil
}

// result gathers the finished files. Files with no resources are left out.
func (g *generator) result() Result {
	files := map[string][]byte{
		fileVersions:  []byte(g.header + versionsBlock),
		fileProviders: []byte(alignEquals(g.header + g.providers.String())),
	}
	addIfNotEmpty := func(name string, body *strings.Builder) {
		if body.Len() > 0 {
			files[name] = []byte(alignEquals(g.header + body.String()))
		}
	}
	addIfNotEmpty(fileNamespaces, g.namespaces)
	addIfNotEmpty(fileMounts, g.mounts)
	addIfNotEmpty(fileAuth, g.auth)
	addIfNotEmpty(filePolicies, g.policies)
	addIfNotEmpty(fileAudit, g.audit)
	addIfNotEmpty(fileImports, g.imports)
	for name, content := range g.policyFiles {
		files[name] = content
	}

	return Result{Files: files, Counts: g.counts, Skipped: g.skipped}
}

// versionsBlock pins Terraform and the provider. Import blocks need
// Terraform 1.5 or later.
// Docs: https://developer.hashicorp.com/terraform/language/import
const versionsBlock = `
terraform {
  required_version = ">= 1.5.0"

  required_providers {
    vault = {
      source  = "hashicorp/vault"
      version = "~> 5.0"
    }
  }
}
`

// writeProviders writes the default provider, plus one alias per namespace.
//
// Resources in a namespace use that namespace's provider alias, so their
// import IDs are plain paths. The provider docs describe this approach for
// importing namespaced resources.
// Docs: https://registry.terraform.io/providers/hashicorp/vault/latest/docs#importing-namespaced-resources
func (g *generator) writeProviders() {
	fmt.Fprintf(g.providers, "\n# Vault address and token come from VAULT_ADDR and VAULT_TOKEN.\nprovider \"vault\" {}\n")

	for _, namespace := range g.inventory.Namespaces {
		if namespace.Path == "" {
			continue
		}
		alias := g.uniqueName("ns_" + sanitizeName(namespace.Path))
		g.aliases[namespace.Path] = alias
		fmt.Fprintf(g.providers, "\nprovider \"vault\" {\n  alias = %s\n  namespace = %s\n}\n",
			quote(alias), quote(strings.TrimSuffix(namespace.Path, "/")))
	}
}

// writeNamespace writes a vault_namespace. It is created with the provider of
// its parent namespace, and its path is relative to that parent.
func (g *generator) writeNamespace(fullPath string) {
	trimmed := strings.TrimSuffix(fullPath, "/")
	parent := ""
	name := trimmed
	lastSlash := strings.LastIndex(trimmed, "/")
	if lastSlash >= 0 {
		parent = trimmed[:lastSlash+1]
		name = trimmed[lastSlash+1:]
	}

	resourceName := g.uniqueName("namespace_" + sanitizeName(trimmed))
	fmt.Fprintf(g.namespaces, "\nresource \"vault_namespace\" %s {\n%s  path = %s\n}\n",
		quote(resourceName), g.providerLine(parent), quote(name))
	g.writeImport("vault_namespace", resourceName, parent, name)
	g.counts.Namespaces++
}

// writeSecretsEngine writes a vault_mount.
// Docs: https://registry.terraform.io/providers/hashicorp/vault/latest/docs/resources/mount
func (g *generator) writeSecretsEngine(namespace string, mount scan.Mount) {
	if builtInSecretsEngines[mount.Path] {
		return
	}
	mountPath := strings.TrimSuffix(mount.Path, "/")
	resourceName := g.uniqueName(namespacePrefix(namespace) + "mount_" + sanitizeName(mountPath))

	body := &strings.Builder{}
	fmt.Fprint(body, g.providerLine(namespace))
	writeAttribute(body, "path", quote(mountPath))
	writeAttribute(body, "type", quote(mount.Type))
	if mount.Description != "" {
		writeAttribute(body, "description", quote(mount.Description))
	}
	if mount.Config.DefaultLeaseTTL != 0 {
		writeAttribute(body, "default_lease_ttl_seconds", fmt.Sprint(mount.Config.DefaultLeaseTTL))
	}
	if mount.Config.MaxLeaseTTL != 0 {
		writeAttribute(body, "max_lease_ttl_seconds", fmt.Sprint(mount.Config.MaxLeaseTTL))
	}
	if mount.Local {
		writeAttribute(body, "local", "true")
	}
	if mount.SealWrap {
		writeAttribute(body, "seal_wrap", "true")
	}
	if mount.ExternalEntropyAccess {
		writeAttribute(body, "external_entropy_access", "true")
	}
	if mount.PluginVersion != "" {
		writeAttribute(body, "plugin_version", quote(mount.PluginVersion))
	}
	if mount.Config.ForceNoCache {
		writeAttribute(body, "force_no_cache", "true")
	}
	if mount.Config.ListingVisibility != "" {
		writeAttribute(body, "listing_visibility", quote(mount.Config.ListingVisibility))
	}
	writeListAttribute(body, "passthrough_request_headers", mount.Config.PassthroughRequestHeaders)
	writeListAttribute(body, "allowed_response_headers", mount.Config.AllowedResponseHeaders)
	writeListAttribute(body, "audit_non_hmac_request_keys", mount.Config.AuditNonHMACRequestKeys)
	writeListAttribute(body, "audit_non_hmac_response_keys", mount.Config.AuditNonHMACResponseKeys)
	writeListAttribute(body, "allowed_managed_keys", mount.Config.AllowedManagedKeys)
	writeListAttribute(body, "delegated_auth_accessors", mount.Config.DelegatedAuthAccessors)
	if mount.Config.IdentityTokenKey != "" {
		writeAttribute(body, "identity_token_key", quote(mount.Config.IdentityTokenKey))
	}
	if len(mount.Options) > 0 {
		writeAttribute(body, "options", stringMap(mount.Options))
	}

	fmt.Fprintf(g.mounts, "\nresource \"vault_mount\" %s {\n%s}\n", quote(resourceName), body.String())
	g.writeImport("vault_mount", resourceName, namespace, mountPath)
	g.counts.SecretsEngines++
}

// writeAuthMethod writes a vault_auth_backend. Method settings, such as LDAP
// or OIDC configuration, have their own resources and are not written.
// Docs: https://registry.terraform.io/providers/hashicorp/vault/latest/docs/resources/auth_backend
func (g *generator) writeAuthMethod(namespace string, mount scan.Mount) {
	if builtInAuthMethods[mount.Path] {
		return
	}
	mountPath := strings.TrimSuffix(mount.Path, "/")
	resourceName := g.uniqueName(namespacePrefix(namespace) + "auth_" + sanitizeName(mountPath))

	body := &strings.Builder{}
	fmt.Fprint(body, g.providerLine(namespace))
	writeAttribute(body, "path", quote(mountPath))
	writeAttribute(body, "type", quote(mount.Type))
	if mount.Description != "" {
		writeAttribute(body, "description", quote(mount.Description))
	}
	if mount.Local {
		writeAttribute(body, "local", "true")
	}

	// The tune block holds TTLs and the token type. Durations are strings,
	// written the way the provider reads them back from Vault ("1h", not
	// "3600s"), or the plan would show a change for every imported TTL.
	tune := &strings.Builder{}
	if mount.Config.DefaultLeaseTTL != 0 {
		fmt.Fprintf(tune, "    default_lease_ttl = %s\n", quote(providerDuration(mount.Config.DefaultLeaseTTL)))
	}
	if mount.Config.MaxLeaseTTL != 0 {
		fmt.Fprintf(tune, "    max_lease_ttl = %s\n", quote(providerDuration(mount.Config.MaxLeaseTTL)))
	}
	if mount.Config.TokenType != "" {
		fmt.Fprintf(tune, "    token_type = %s\n", quote(mount.Config.TokenType))
	}
	if mount.Config.ListingVisibility != "" {
		fmt.Fprintf(tune, "    listing_visibility = %s\n", quote(mount.Config.ListingVisibility))
	}
	tuneLists := []struct {
		name   string
		values []string
	}{
		{"passthrough_request_headers", mount.Config.PassthroughRequestHeaders},
		{"allowed_response_headers", mount.Config.AllowedResponseHeaders},
		{"audit_non_hmac_request_keys", mount.Config.AuditNonHMACRequestKeys},
		{"audit_non_hmac_response_keys", mount.Config.AuditNonHMACResponseKeys},
	}
	for _, tuneList := range tuneLists {
		if len(tuneList.values) > 0 {
			fmt.Fprintf(tune, "    %s = %s\n", tuneList.name, stringList(tuneList.values))
		}
	}
	if tune.Len() > 0 {
		fmt.Fprintf(body, "\n  tune {\n%s  }\n", tune.String())
	}

	fmt.Fprintf(g.auth, "\nresource \"vault_auth_backend\" %s {\n%s}\n", quote(resourceName), body.String())
	g.writeImport("vault_auth_backend", resourceName, namespace, mountPath)
	g.counts.AuthMethods++
}

// writePolicy writes a vault_policy whose text lives in its own .hcl file,
// so policies can be reviewed in git as policy files.
// Docs: https://registry.terraform.io/providers/hashicorp/vault/latest/docs/resources/policy
func (g *generator) writePolicy(namespace string, policy scan.Policy) error {
	if policy.Name == rootPolicyName {
		return nil
	}

	resourceName := g.uniqueName(namespacePrefix(namespace) + "policy_" + sanitizeName(policy.Name))
	folder := "root"
	if namespace != "" {
		folder = sanitizeFileName(strings.TrimSuffix(namespace, "/"))
	}
	fileName := path.Join(policyFolder, folder, sanitizeFileName(policy.Name)+".hcl")
	_, taken := g.policyFiles[fileName]
	if taken {
		return fmt.Errorf("two policies in namespace %q map to the same file name %s; rename one of them in Vault", namespaceLabel(namespace), fileName)
	}

	// The file holds exactly the text Vault returned. Adding a final line
	// break would make the plan show a change, because the provider compares
	// the file's text with Vault's text byte for byte.
	g.policyFiles[fileName] = []byte(policy.Text)

	fmt.Fprintf(g.policies, "\nresource \"vault_policy\" %s {\n%s  name = %s\n  policy = file(\"${path.module}/%s\")\n}\n",
		quote(resourceName), g.providerLine(namespace), quote(policy.Name), escapeTemplate(fileName))
	g.writeImport("vault_policy", resourceName, namespace, policy.Name)
	g.counts.Policies++
	return nil
}

// writeAuditDevice writes a vault_audit. Audit devices exist only in the
// root namespace.
// Docs: https://registry.terraform.io/providers/hashicorp/vault/latest/docs/resources/audit
func (g *generator) writeAuditDevice(device scan.AuditDevice) {
	devicePath := strings.TrimSuffix(device.Path, "/")
	resourceName := g.uniqueName("audit_" + sanitizeName(devicePath))

	body := &strings.Builder{}
	writeAttribute(body, "path", quote(devicePath))
	writeAttribute(body, "type", quote(device.Type))
	if device.Description != "" {
		writeAttribute(body, "description", quote(device.Description))
	}
	if device.Local {
		writeAttribute(body, "local", "true")
	}
	writeAttribute(body, "options", stringMap(device.Options))

	fmt.Fprintf(g.audit, "\nresource \"vault_audit\" %s {\n%s}\n", quote(resourceName), body.String())
	g.writeImport("vault_audit", resourceName, "", devicePath)
	g.counts.AuditDevices++
}

// writeImport adds an import block, so "terraform apply" adopts the existing
// object instead of creating a new one.
// Docs: https://developer.hashicorp.com/terraform/language/import
func (g *generator) writeImport(resourceType string, resourceName string, namespace string, importID string) {
	fmt.Fprintf(g.imports, "\nimport {\n%s  to = %s.%s\n  id = %s\n}\n",
		g.providerLine(namespace), resourceType, resourceName, quote(importID))
}

// noteSkippedChecks records parts of a namespace the scan could not read,
// because they are then missing from the generated configuration.
func (g *generator) noteSkippedChecks(namespace string) {
	for _, skipped := range g.inventory.Skipped {
		if skipped.Namespace != namespace {
			continue
		}
		g.skipped = append(g.skipped, fmt.Sprintf("%s in namespace %s: the scan could not read it (%s)", skipped.Check, namespaceLabel(namespace), skipped.Reason))
	}
}

// providerLine returns the "provider = vault.alias" line for a namespace, or
// nothing for the root namespace.
func (g *generator) providerLine(namespace string) string {
	if namespace == "" {
		return ""
	}
	return fmt.Sprintf("  provider = vault.%s\n", g.aliases[namespace])
}

// uniqueName returns a resource name that has not been used yet, adding a
// number when two Vault names turn into the same Terraform name.
func (g *generator) uniqueName(base string) string {
	name := base
	for counter := 2; g.usedNames[name]; counter++ {
		name = fmt.Sprintf("%s_%d", base, counter)
	}
	g.usedNames[name] = true
	return name
}

// providerDuration writes a number of seconds the way the Vault provider
// writes auth method TTLs into Terraform state: Go's duration text with
// trailing zero units removed, so 3600 is "1h", 5400 is "1h30m" and 90 is
// "1m30s". This copies util.ShortDur from the provider.
// Source: https://github.com/hashicorp/terraform-provider-vault/blob/v5.13.0/util/util.go
func providerDuration(seconds int64) string {
	text := (time.Duration(seconds) * time.Second).String()
	if strings.HasSuffix(text, "m0s") {
		text = strings.TrimSuffix(text, "0s")
	}
	if strings.HasSuffix(text, "h0m") {
		text = strings.TrimSuffix(text, "0m")
	}
	return text
}

// attributeLine matches a one-line "name = value" inside a block, so
// alignEquals can line up the "=" signs.
var attributeLine = regexp.MustCompile(`^(\s*)([A-Za-z0-9_"-]+) = (.*)$`)

// alignEquals lines up the "=" signs of neighbouring one-line attributes,
// the way "terraform fmt" does, so the files pass "terraform fmt -check".
// A blank line, a block, or an attribute whose value spans several lines
// (it ends in "{") starts a new group.
// Docs: https://developer.hashicorp.com/terraform/cli/commands/fmt
func alignEquals(text string) string {
	lines := strings.Split(text, "\n")
	groupStart := -1
	groupIndent := ""

	flush := func(end int) {
		if groupStart < 0 {
			return
		}
		longest := 0
		for _, line := range lines[groupStart:end] {
			match := attributeLine.FindStringSubmatch(line)
			if len(match[2]) > longest {
				longest = len(match[2])
			}
		}
		for index := groupStart; index < end; index++ {
			match := attributeLine.FindStringSubmatch(lines[index])
			lines[index] = match[1] + match[2] + strings.Repeat(" ", longest-len(match[2])) + " = " + match[3]
		}
		groupStart = -1
	}

	for index, line := range lines {
		match := attributeLine.FindStringSubmatch(line)
		isSingleLineAttribute := match != nil && !strings.HasSuffix(match[3], "{")
		if !isSingleLineAttribute || (groupStart >= 0 && match[1] != groupIndent) {
			flush(index)
		}
		if isSingleLineAttribute && groupStart < 0 {
			groupStart = index
			groupIndent = match[1]
		}
	}
	flush(len(lines))
	return strings.Join(lines, "\n")
}

// writeAttribute writes one "name = value" line inside a block.
func writeAttribute(body *strings.Builder, name string, value string) {
	fmt.Fprintf(body, "  %s = %s\n", name, value)
}

// writeListAttribute writes "name = [...]" when values is not empty. An empty
// list is left out, which matches what the provider reads for an unset value.
func writeListAttribute(body *strings.Builder, name string, values []string) {
	if len(values) == 0 {
		return
	}
	writeAttribute(body, name, stringList(values))
}

// stringList writes a list of strings as a one-line HCL list, in the order
// Vault returned them.
func stringList(values []string) string {
	quoted := make([]string, 0, len(values))
	for _, value := range values {
		quoted = append(quoted, quote(value))
	}
	return "[" + strings.Join(quoted, ", ") + "]"
}

// stringMap writes a map of strings as an HCL object, keys sorted.
func stringMap(values map[string]string) string {
	if len(values) == 0 {
		return "{}"
	}
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)

	text := &strings.Builder{}
	text.WriteString("{\n")
	for _, key := range keys {
		fmt.Fprintf(text, "    %s = %s\n", quote(key), quote(values[key]))
	}
	text.WriteString("  }")
	return text.String()
}

// quote writes a Terraform string literal. Besides the usual escapes,
// "${" and "%{" are doubled so Terraform does not treat them as templates.
// Docs: https://developer.hashicorp.com/terraform/language/expressions/strings#escape-sequences
func quote(value string) string {
	text := &strings.Builder{}
	text.WriteByte('"')
	for _, character := range value {
		switch character {
		case '\\':
			text.WriteString(`\\`)
		case '"':
			text.WriteString(`\"`)
		case '\n':
			text.WriteString(`\n`)
		case '\r':
			text.WriteString(`\r`)
		case '\t':
			text.WriteString(`\t`)
		default:
			if character < 0x20 || character == 0x7f {
				fmt.Fprintf(text, `\u%04x`, character)
				continue
			}
			text.WriteRune(character)
		}
	}
	text.WriteByte('"')
	return escapeTemplate(text.String())
}

// escapeTemplate doubles "${" and "%{" so Terraform reads them literally.
func escapeTemplate(text string) string {
	text = strings.ReplaceAll(text, "${", "$${")
	text = strings.ReplaceAll(text, "%{", "%%{")
	return text
}

// invalidNameCharacters matches what Terraform does not allow in a resource name.
var invalidNameCharacters = regexp.MustCompile(`[^a-z0-9_]+`)

// sanitizeName turns a Vault path or name into a valid Terraform resource
// name: lowercase letters, digits and underscores, starting with a letter.
// Docs: https://developer.hashicorp.com/terraform/language/syntax/configuration#identifiers
func sanitizeName(value string) string {
	name := invalidNameCharacters.ReplaceAllString(strings.ToLower(value), "_")
	name = strings.Trim(name, "_")
	if name == "" {
		name = "unnamed"
	}
	if name[0] >= '0' && name[0] <= '9' {
		name = "n_" + name
	}
	return name
}

// invalidFileCharacters matches what is not safe in a file name on every
// platform Mitch runs on.
var invalidFileCharacters = regexp.MustCompile(`[^A-Za-z0-9._-]+`)

// sanitizeFileName makes a Vault name safe to use as one file or folder name.
// Slashes become underscores, so a name can never point outside its folder.
func sanitizeFileName(value string) string {
	name := invalidFileCharacters.ReplaceAllString(value, "_")
	name = strings.Trim(name, ".")
	if name == "" {
		name = "unnamed"
	}
	return name
}

// namespacePrefix starts resource names in a namespace with the namespace,
// so the same mount path in two namespaces gets two names.
func namespacePrefix(namespace string) string {
	if namespace == "" {
		return ""
	}
	return sanitizeName(namespace) + "_"
}

// namespaceLabel shows the root namespace as "(root)".
func namespaceLabel(namespace string) string {
	if namespace == "" {
		return "(root)"
	}
	return namespace
}
